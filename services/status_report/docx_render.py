def _t(key: str, en: bool) -> str:
    return _TXT[key][1 if en else 0]


def _status(code: str, en: bool) -> str:
    return _STATUS[code][1 if en else 0]


def _table(doc, header: list, rows: list):
    table = doc.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    for i, h in enumerate(header):
        cell = table.rows[0].cells[i]
        cell.paragraphs[0].add_run(str(h)).bold = True
        _set_cell_background(cell, "f8fafc")
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = "" if value is None else str(value)
    for row in table.rows:
        for cell in row.cells:
            for p in cell.paragraphs:
                for run in p.runs:
                    run.font.size = Pt(8.5)
    return table


def _status_cell(cell, code: str, en: bool):
    cell.text = _status(code, en)
    _set_cell_background(cell, _STATUS[code][2])


def _controls_text(controls: dict, frameworks: dict) -> str:
    short = {"nis2": "NIS2", "ir2690": "2024/2690", "iso27001": "ISO 27001",
             "cis8": "CIS v8", "iec62443": "IEC 62443"}
    return "; ".join(f"{short.get(fw, fw)} {', '.join(ids)}" for fw, ids in controls.items()
                     if fw in frameworks)


def render(snapshot: dict, lang: str = "it") -> bytes:
    en = lang == "en"
    k = "en" if en else "it"
    # Labels are presentation only: the snapshot keeps the raw keys.
    labels = load_mapping().get("labels", {})

    def _lbl(key: str) -> str:
        return labels.get(key, {}).get(k, key)

    refs = snapshot["references"]
    evidence = snapshot["evidence"]
    doc = Document()

    # 1. Cover
    title = doc.add_heading(f"SentinelNet  |  {_t('title', en)}", level=0)
    title.runs[0].font.color.rgb = RGBColor(15, 23, 42)
    _table(doc, [_t("tenant", en), _t("generated", en), _t("period", en), _t("by", en), _t("version", en)],
           [[snapshot["tenant"], snapshot["generated_at"], f"{snapshot['period_days']} {_t('days', en)}",
             snapshot["generated_by"], snapshot["app_version"]]])
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    run = p.add_run(_t("disclaimer", en))
    run.bold = True
    run.font.size = Pt(10)

    # 2. Summary
    doc.add_heading(_t("summary", en), level=1)
    table = _table(doc, [_t("evidence", en), _t("status", en), _t("controls", en)],
                   [[e["title"][k], "",
                     _controls_text(e["controls"], refs["frameworks"])] for e in evidence.values()])
    for row, e in zip(table.rows[1:], evidence.values()):
        _status_cell(row.cells[1], e["status"], en)

    # 3. Per framework
    doc.add_heading(_t("by_framework", en), level=1)
    for fw, fw_title in refs["frameworks"].items():
        doc.add_heading(fw_title[k], level=2)
        rows, statuses = [], []
        for cid, ctitle in refs["controls"].get(fw, {}).items():
            for e in evidence.values():
                if cid in e["controls"].get(fw, []):
                    label = ctitle[k]
                    if ctitle.get("verify"):
                        label += f" ({_t('verify', en)})"
                    rows.append([cid, label, e["title"][k], ""])
                    statuses.append(e["status"])
        table = _table(doc, [_t("control", en), _t("ctitle", en), _t("evidence", en), _t("status", en)], rows)
        for row, code in zip(table.rows[1:], statuses):
            _status_cell(row.cells[3], code, en)

    # 4. Evidence detail
    doc.add_heading(_t("detail", en), level=1)
    for e in evidence.values():
        doc.add_heading(f"{e['title'][k]} - {_status(e['status'], en)}", level=2)
        if e.get("note"):
            doc.add_paragraph(e["note"][k])
        if e["metrics"]:
            doc.add_paragraph(_t("metrics", en)).runs[0].bold = True
            _table(doc, ["", ""], [[_lbl(name), ", ".join(map(str, v)) if isinstance(v, list) else v]
                                   for name, v in e["metrics"].items()])
        rows = e["rows"]
        if not rows:
            doc.add_paragraph(_t("no_rows", en))
            continue
        shown = rows[:ROW_CAP]
        doc.add_paragraph()
        _table(doc, [_lbl(c) for c in shown[0]], [list(r.values()) for r in shown])
        if len(rows) > ROW_CAP:
            doc.add_paragraph(_t("capped", en).format(shown=ROW_CAP, total=len(rows)))

    # 5. Outside the technical scope (always printed)
    doc.add_heading(_t("out_of_scope", en), level=1)
    doc.add_paragraph(_t("out_intro", en))
    for item in refs["out_of_scope"]:
        doc.add_paragraph(f"{item['ref']}: {item[k]}", style="List Bullet")

    # 6. Method
    doc.add_heading(_t("method", en), level=1)
    doc.add_paragraph(_t("method_intro", en).format(mv=snapshot["mapping_version"]))
    rows = []
    for e in evidence.values():
        rules = [f"{r['status']} if {r['metric']} {r['op']} {r['value']}" for r in e["rules"]]
        rules.append(f"{_t('otherwise', en)} {e['default']}; {_t('unavailable_if', en)}")
        rows.append([e["title"][k], e["source"][k],
                     e["collected_at"], "; ".join(rules)])
    _table(doc, [_t("evidence", en), _t("source", en), _t("collected", en), _t("thresholds", en)], rows)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
