"""Definizioni dei benchmark: metadati che legano una citazione a una regola.

Regole condivise fra benchmark (es. la versione TLS vale sia per CIS sia per
NIST SC-13) puntano alla STESSA funzione: cambia solo la citazione, il titolo e
il testo di rimedio. Nessuna logica e' duplicata.

Nomenclatura: CIS versiona i benchmark per prodotto, non esiste una "CIS
Benchmark v4.0" globale. Le voci ``ref`` citano:

  - *CIS Fortinet FortiGate Benchmark v1.0.1* (vendor ``fortios``)
  - *CIS Cisco IOS XE 17.x Benchmark v2.2.1* (vendor ``ios``)

Campi di ogni voce:

  ``vendor``      piattaforma a cui la regola si applica: ``fortios`` o ``ios``.
                  Il motore scarta le regole di un vendor diverso da quello
                  riconosciuto nella configurazione, invece di valutarle e
                  produrre un UNKNOWN che non significa niente.
  ``ref``         numero di raccomandazione nel benchmark di origine, vuoto se
                  la regola non ne ha uno (NIST/PCI usano il proprio codice
                  nel titolo).
  ``level``       profilo CIS: 1 = applicabile ovunque, 2 = ambienti ad alta
                  sicurezza, con possibile impatto funzionale.
  ``automated``   il benchmark la marca come verificabile automaticamente.
                  ``False`` significa che il documento la vuole verificata a
                  mano: qui esiste comunque un controllo, ma su cio' che la
                  configurazione dichiara, non sul comportamento reale.
  ``audit``       comando CLI del benchmark per verificare a mano sull'apparato.
  ``remediation`` comando CLI per rimediare.
"""

